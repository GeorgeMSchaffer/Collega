// A dated grouping lens over top-level items (SPEC/contracts/outcomes.md). Org-scoped and
// soft-deletable, not a container: no status, no sprint, and an item sits under at most one.
//
// Immutable data plus transition functions, per packages/domain/src/common.

import { type Auditable, markCreated, markUpdated } from '../common/index.js'

export const OUTCOME_NAME_MAX_LENGTH = 120
export const OUTCOME_DESCRIPTION_MAX_LENGTH = 1000

/** Mirrors `SprintInvariantError` so the Application layer can key a 400 on `field`. */
export class OutcomeInvariantError extends Error {
  readonly field: string

  constructor(field: string, message: string) {
    super(message)
    this.name = 'OutcomeInvariantError'
    this.field = field
  }
}

export type Outcome = Auditable & {
  readonly id: string
  readonly organizationId: string
  /** Required. Not unique (decision 4). */
  readonly name: string
  readonly description: string | null
  /** `YYYY-MM-DD`; the repository converts to a `date` column. */
  readonly targetStartDate: string
  readonly targetEndDate: string
  readonly ownerUserId: string | null
  readonly sortOrder: number
  /** `#RRGGBB`, upper case. */
  readonly color: string
  readonly isDeleted: boolean
}

export type OutcomeFields = {
  readonly name: string
  readonly description: string | null
  readonly targetStartDate: string
  readonly targetEndDate: string
  readonly ownerUserId: string | null
}

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/
const HEX_COLOR = /^#[0-9A-Fa-f]{6}$/

function requireName(value: string): string {
  const trimmed = value.trim()
  if (trimmed.length === 0) {
    throw new OutcomeInvariantError('name', 'Name is required.')
  }
  if (trimmed.length > OUTCOME_NAME_MAX_LENGTH) {
    throw new OutcomeInvariantError(
      'name',
      `Name must be ${OUTCOME_NAME_MAX_LENGTH} characters or fewer.`,
    )
  }
  return trimmed
}

function optionalDescription(value: string | null): string | null {
  const trimmed = value?.trim() ?? ''
  if (trimmed.length === 0) {
    return null
  }
  if (trimmed.length > OUTCOME_DESCRIPTION_MAX_LENGTH) {
    throw new OutcomeInvariantError(
      'description',
      `Description must be ${OUTCOME_DESCRIPTION_MAX_LENGTH} characters or fewer.`,
    )
  }
  return trimmed
}

function requireDate(value: string, field: string, label: string): string {
  if (value.trim().length === 0) {
    throw new OutcomeInvariantError(field, `${label} is required.`)
  }
  const parsed = new Date(`${value}T00:00:00.000Z`)
  if (
    !ISO_DATE.test(value) ||
    Number.isNaN(parsed.getTime()) ||
    parsed.toISOString().slice(0, 10) !== value
  ) {
    throw new OutcomeInvariantError(field, `${label} must be a valid date.`)
  }
  return value
}

/** The trimmed fields, with the window checked (end on or after start). */
function checkFields(fields: OutcomeFields): OutcomeFields {
  const name = requireName(fields.name)
  const description = optionalDescription(fields.description)
  const targetStartDate = requireDate(
    fields.targetStartDate,
    'targetStartDate',
    'Target Start Date',
  )
  const targetEndDate = requireDate(fields.targetEndDate, 'targetEndDate', 'Target End Date')
  if (targetEndDate < targetStartDate) {
    throw new OutcomeInvariantError('targetEndDate', 'End date must be on or after start date.')
  }
  return { name, description, targetStartDate, targetEndDate, ownerUserId: fields.ownerUserId }
}

/** Any `#RRGGBB`, stored upper case; anything else is refused on `color`. */
export function normalizeOutcomeColor(color: string): string {
  if (!HEX_COLOR.test(color)) {
    throw new OutcomeInvariantError('color', 'Color must be a valid #RRGGBB color.')
  }
  return color.toUpperCase()
}

export function createOutcome(
  params: OutcomeFields & {
    /** Generated by the Application layer with `crypto.randomUUID()`. */
    readonly id: string
    readonly organizationId: string
    readonly sortOrder: number
    readonly color: string
    readonly nowUtc: Date
    readonly actorUserId: string | null
  },
): Outcome {
  const fields = checkFields(params)
  return {
    id: params.id,
    organizationId: params.organizationId,
    ...fields,
    sortOrder: params.sortOrder,
    color: normalizeOutcomeColor(params.color),
    isDeleted: false,
    ...markCreated(params.nowUtc, params.actorUserId),
  }
}

/** A full replacement of the fields; `color` `null` keeps the stored colour. */
export function updateOutcome(
  outcome: Outcome,
  params: OutcomeFields & { readonly color: string | null },
  nowUtc: Date,
  actorUserId: string | null,
): Outcome {
  if (outcome.isDeleted) {
    throw new OutcomeInvariantError('outcome', 'A deleted outcome cannot be updated.')
  }
  const fields = checkFields(params)
  const color = params.color === null ? outcome.color : normalizeOutcomeColor(params.color)
  return markUpdated({ ...outcome, ...fields, color }, nowUtc, actorUserId)
}

export function setOutcomeSortOrder(
  outcome: Outcome,
  sortOrder: number,
  nowUtc: Date,
  actorUserId: string | null,
): Outcome {
  return markUpdated({ ...outcome, sortOrder }, nowUtc, actorUserId)
}

/** Idempotent soft delete; ungrouping the items is the Application layer's. */
export function softDeleteOutcome(
  outcome: Outcome,
  nowUtc: Date,
  actorUserId: string | null,
): Outcome {
  if (outcome.isDeleted) {
    return outcome
  }
  return markUpdated({ ...outcome, isDeleted: true }, nowUtc, actorUserId)
}
