// An organization-scoped, archivable kind of value an item can carry (SPEC/contracts/metric-types.md).
// Names may repeat; there is no delete, only archive.
//
// Immutable data plus transition functions, per packages/domain/src/common.

import { type Auditable, markCreated, markUpdated } from '../common/index.js'

export const METRIC_TYPE_NAME_MAX_LENGTH = 80
export const METRIC_TYPE_UNIT_MAX_LENGTH = 20

/** Stored `numeric(17,2)`: an absolute value below 10^15 and at most two decimal places. */
const METRIC_VALUE_LIMIT = 1e15
export const METRIC_VALUE_MAX_DECIMALS = 2

export class MetricTypeInvariantError extends Error {
  readonly field: string

  constructor(field: string, message: string) {
    super(message)
    this.name = 'MetricTypeInvariantError'
    this.field = field
  }
}

export type MetricType = Auditable & {
  readonly id: string
  readonly organizationId: string
  readonly name: string
  readonly unit: string | null
  readonly isArchived: boolean
}

export type MetricTypeFields = {
  readonly name: string
  readonly unit: string | null
}

function checkFields(fields: MetricTypeFields): MetricTypeFields {
  const name = fields.name.trim()
  if (name.length === 0) {
    throw new MetricTypeInvariantError('name', 'Name is required.')
  }
  if (name.length > METRIC_TYPE_NAME_MAX_LENGTH) {
    throw new MetricTypeInvariantError(
      'name',
      `Name must be ${METRIC_TYPE_NAME_MAX_LENGTH} characters or fewer.`,
    )
  }
  const unit = fields.unit?.trim() ?? ''
  if (unit.length > METRIC_TYPE_UNIT_MAX_LENGTH) {
    throw new MetricTypeInvariantError(
      'unit',
      `Unit must be ${METRIC_TYPE_UNIT_MAX_LENGTH} characters or fewer.`,
    )
  }
  return { name, unit: unit.length === 0 ? null : unit }
}

export function createMetricType(
  params: MetricTypeFields & {
    /** Generated by the Application layer with `crypto.randomUUID()`. */
    readonly id: string
    readonly organizationId: string
    readonly nowUtc: Date
    readonly actorUserId: string | null
  },
): MetricType {
  return {
    id: params.id,
    organizationId: params.organizationId,
    ...checkFields(params),
    isArchived: false,
    ...markCreated(params.nowUtc, params.actorUserId),
  }
}

/** A full replacement of name, unit and archive state. */
export function updateMetricType(
  metricType: MetricType,
  params: MetricTypeFields & { readonly isArchived: boolean },
  nowUtc: Date,
  actorUserId: string | null,
): MetricType {
  return markUpdated(
    { ...metricType, ...checkFields(params), isArchived: params.isArchived },
    nowUtc,
    actorUserId,
  )
}

/**
 * Checks one projected or realized number against the stored range and precision, keyed on
 * `metrics`. The shortest round-trip text of a double is what the caller typed, so counting its
 * decimals is exact where multiplying by 100 is not; exponent form below 10^15 is only ever a
 * value under 10^-6. (A double cannot hold 999999999999999.99: it parses as 10^15 and is refused.)
 */
export function checkMetricNumber(label: 'Projected' | 'Realized', value: number): void {
  if (!Number.isFinite(value) || Math.abs(value) >= METRIC_VALUE_LIMIT) {
    throw new MetricTypeInvariantError(
      'metrics',
      `${label} must be between -999999999999999.99 and 999999999999999.99.`,
    )
  }
  const text = String(value)
  const decimals = text.includes('e') ? Number.POSITIVE_INFINITY : (text.split('.')[1]?.length ?? 0)
  if (decimals > METRIC_VALUE_MAX_DECIMALS) {
    throw new MetricTypeInvariantError(
      'metrics',
      `${label} must have at most ${METRIC_VALUE_MAX_DECIMALS} decimal places.`,
    )
  }
}
