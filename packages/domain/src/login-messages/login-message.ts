// A message shown on the desk after sign-in (SPEC/20-feature-login-messages.md). A null
// `organizationId` is a system message.
//
// Immutable data plus transition functions, per packages/domain/src/common.

import { type Auditable, markCreated, markUpdated } from '../common/index.js'
import { LoginMessageDismissal, LoginMessageDisplay } from '../enums/index.js'

export const LOGIN_MESSAGE_TITLE_MAX_LENGTH = 120
export const LOGIN_MESSAGE_BODY_MAX_LENGTH = 4000

const DISPLAYS: readonly string[] = Object.values(LoginMessageDisplay)
const DISMISSAL_MODES: readonly string[] = Object.values(LoginMessageDismissal)

export type LoginMessageState = 'Scheduled' | 'Live' | 'Ended'

export class LoginMessageInvariantError extends Error {
  readonly field: string

  constructor(field: string, message: string) {
    super(message)
    this.name = 'LoginMessageInvariantError'
    this.field = field
  }
}

export type LoginMessage = Auditable & {
  readonly id: string
  readonly organizationId: string | null
  readonly title: string
  readonly body: string
  readonly display: LoginMessageDisplay
  readonly dismissalMode: LoginMessageDismissal
  readonly startsAtUtc: Date
  readonly endsAtUtc: Date | null
  readonly revision: number
}

export type LoginMessageFields = {
  readonly title: string
  readonly body: string
  readonly display: string
  readonly dismissalMode: string
  readonly startsAtUtc: Date
  readonly endsAtUtc: Date | null
}

/** A user's record against one message (LMS-4). */
export type LoginMessageReceipt = {
  readonly messageId: string
  readonly userId: string
  readonly revision: number
  readonly closedAtUtc: Date | null
  readonly dismissedAtUtc: Date | null
  readonly acknowledgedAtUtc: Date | null
}

type CheckedFields = Omit<LoginMessageFields, 'display' | 'dismissalMode'> & {
  readonly display: LoginMessageDisplay
  readonly dismissalMode: LoginMessageDismissal
}

function checkText(field: string, label: string, value: string, max: number): string {
  const trimmed = value.trim()
  if (trimmed.length === 0) {
    throw new LoginMessageInvariantError(field, `${label} is required.`)
  }
  if (trimmed.length > max) {
    throw new LoginMessageInvariantError(field, `${label} must be ${max} characters or fewer.`)
  }
  return trimmed
}

function isValidDate(value: Date | null): value is Date {
  return value instanceof Date && !Number.isNaN(value.getTime())
}

function checkFields(fields: LoginMessageFields): CheckedFields {
  const title = checkText('title', 'Title', fields.title, LOGIN_MESSAGE_TITLE_MAX_LENGTH)
  const body = checkText('body', 'Body', fields.body, LOGIN_MESSAGE_BODY_MAX_LENGTH)
  if (!DISPLAYS.includes(fields.display)) {
    throw new LoginMessageInvariantError('display', 'Display must be Modal or Banner.')
  }
  if (!DISMISSAL_MODES.includes(fields.dismissalMode)) {
    throw new LoginMessageInvariantError(
      'dismissalMode',
      'Dismissal mode must be EveryLogin, DismissOnce or AcknowledgeRequired.',
    )
  }
  if (!isValidDate(fields.startsAtUtc)) {
    throw new LoginMessageInvariantError('startsAtUtc', 'Start is required.')
  }
  if (fields.endsAtUtc !== null) {
    if (!isValidDate(fields.endsAtUtc)) {
      throw new LoginMessageInvariantError('endsAtUtc', 'End must be a date and time.')
    }
    if (fields.endsAtUtc.getTime() <= fields.startsAtUtc.getTime()) {
      throw new LoginMessageInvariantError('endsAtUtc', 'End must be after start.')
    }
  }
  return {
    title,
    body,
    display: fields.display as LoginMessageDisplay,
    dismissalMode: fields.dismissalMode as LoginMessageDismissal,
    startsAtUtc: fields.startsAtUtc,
    endsAtUtc: fields.endsAtUtc,
  }
}

export function createLoginMessage(
  params: LoginMessageFields & {
    /** Generated by the Application layer with `crypto.randomUUID()`. */
    readonly id: string
    readonly organizationId: string | null
    readonly nowUtc: Date
    readonly actorUserId: string | null
  },
): LoginMessage {
  return {
    id: params.id,
    organizationId: params.organizationId,
    ...checkFields(params),
    revision: 1,
    ...markCreated(params.nowUtc, params.actorUserId),
  }
}

/** A full replacement of the editable fields. `showAgain` raises the revision (LMS-5). */
export function updateLoginMessage(
  message: LoginMessage,
  fields: LoginMessageFields,
  showAgain: boolean,
  nowUtc: Date,
  actorUserId: string | null,
): LoginMessage {
  return markUpdated(
    {
      ...message,
      ...checkFields(fields),
      revision: showAgain ? message.revision + 1 : message.revision,
    },
    nowUtc,
    actorUserId,
  )
}

export function loginMessageState(message: LoginMessage, nowUtc: Date): LoginMessageState {
  if (nowUtc.getTime() < message.startsAtUtc.getTime()) return 'Scheduled'
  if (message.endsAtUtc !== null && nowUtc.getTime() >= message.endsAtUtc.getTime()) return 'Ended'
  return 'Live'
}

export function isLive(message: LoginMessage, nowUtc: Date): boolean {
  return loginMessageState(message, nowUtc) === 'Live'
}

/**
 * LMS-4: hidden when acknowledged, dismissed for good, or closed during this sign-in. A receipt for
 * an older revision counts as none (LMS-5).
 */
export function isHiddenFor(
  message: LoginMessage,
  receipt: LoginMessageReceipt | null,
  signedInAtUtc: Date,
): boolean {
  if (!receipt || receipt.revision !== message.revision) return false
  if (receipt.acknowledgedAtUtc !== null) return true
  if (
    message.dismissalMode === LoginMessageDismissal.DismissOnce &&
    receipt.dismissedAtUtc !== null
  )
    return true
  return receipt.closedAtUtc !== null && receipt.closedAtUtc.getTime() >= signedInAtUtc.getTime()
}

/**
 * Applies a close (LMS-4a–c, f). On `DismissOnce` a close is the dismissal. The first dismissal and
 * acknowledgement are kept; the close time is the latest.
 */
export function recordClose(
  message: LoginMessage,
  userId: string,
  receipt: LoginMessageReceipt | null,
  nowUtc: Date,
): LoginMessageReceipt {
  const current = currentReceipt(message, userId, receipt)
  if (message.dismissalMode === LoginMessageDismissal.DismissOnce) {
    return { ...current, dismissedAtUtc: current.dismissedAtUtc ?? nowUtc }
  }
  return { ...current, closedAtUtc: nowUtc }
}

/** Applies an acknowledgement (LMS-4c). The caller has checked the mode. */
export function recordAcknowledgement(
  message: LoginMessage,
  userId: string,
  receipt: LoginMessageReceipt | null,
  nowUtc: Date,
): LoginMessageReceipt {
  const current = currentReceipt(message, userId, receipt)
  return { ...current, acknowledgedAtUtc: current.acknowledgedAtUtc ?? nowUtc }
}

function currentReceipt(
  message: LoginMessage,
  userId: string,
  receipt: LoginMessageReceipt | null,
): LoginMessageReceipt {
  if (receipt && receipt.revision === message.revision) return receipt
  return {
    messageId: message.id,
    userId,
    revision: message.revision,
    closedAtUtc: null,
    dismissedAtUtc: null,
    acknowledgedAtUtc: null,
  }
}
